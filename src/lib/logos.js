// Dua huruf pertama kode saham, untuk avatar inisial (BBCA -> "BB").
export function stockInitials(code) {
  const c = String(code || "").replace(/[^A-Z0-9]/g, "");
  return c.slice(0, 2) || "??";
}

export function stockLogoURL(code) {
  return LOGO_URLS[code] || null;
}

// Markup logo saham: <img> logo asli di atas avatar inisial oranye.
// Bila gambar gagal dimuat, onerror menghapus <img> dan inisialnya tampil.
export function stockLogoHTML(code, size = 36) {
  const url = LOGO_URLS[code];
  const px = Number(size) || 36;
  const img = url
    ? `<img src="${url}" alt="" loading="lazy" decoding="async" referrerpolicy="no-referrer" onerror="this.remove()">`
    : "";
  return `<span class="stock-logo" style="width:${px}px;height:${px}px" aria-hidden="true"><span class="stock-logo-fallback">${stockInitials(code)}</span>${img}</span>`;
}
